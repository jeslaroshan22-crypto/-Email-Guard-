# --- Email Alert Function ---
def send_login_alert(user_email, status):
    sender_email = "YOUR_REAL_EMAIL@gmail.com"  
    sender_password = "YOUR_16_DIGIT_APP_PASSWORD" 
    receiver_email = "YOUR_REAL_EMAIL@gmail.com" 
    
    try:
        msg = MIMEMultipart()
        msg['From'] = sender_email
        msg['To'] = receiver_email
        msg['Subject'] = f"🚨 EmailGuard Security Alert: Login Attempt ({status})"
        
        body = f"""
        Hello Admin,
        
        A login attempt was made on your EmailGuard Security Suite dashboard.
        
        - Attempted Email: {user_email}
        - Status: {status}
        - Timestamp: {datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
        
        If this was you, you can safely ignore this message. If not, please secure your system immediately!
        """
        msg.attach(MIMEText(body, 'plain'))
        
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(sender_email, sender_password)
        server.sendmail(sender_email, receiver_email, msg.as_string())
        server.quit()
    except Exception as e:
        print(f"Email alert failed: {e}")

