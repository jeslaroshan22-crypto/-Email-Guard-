DB_FILE = "alias_database.json"

def load_alias_data():
    if os.path.exists(DB_FILE):
        with open(DB_FILE, 'r') as f:
            return json.load(f)
    return {}

def save_alias_data(data):
    with open(DB_FILE, 'w') as f:
        json.dump(data, f, indent=4)

def get_ip_geolocation(ip_address):
    try:
        response = requests.get(f"http://ip-api.com/json/{ip_address}", timeout=5)
        data = response.json()
        if data.get("status") == "success":
            return data.get("country", "Unknown"), data.get("isp", "Unknown")
    except Exception:
        pass
    return "Unknown", "Unknown"

def generate_forensic_report(report_data, output_filename="Email_Forensic_Report.pdf"):
    doc = SimpleDocTemplate(output_filename, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
    story = []
    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], fontSize=18, textColor=colors.HexColor("#0284c7"), alignment=1, spaceAfter=15)
    heading_style = ParagraphStyle('HeadingStyle', parent=styles['Heading2'], fontSize=13, textColor=colors.HexColor("#0369a1"), spaceBefore=10, spaceAfter=6)
    normal_style = styles['Normal']
    
    story.append(Paragraph("EMAIL SECURITY & FORENSIC REPORT", title_style))
    story.append(Paragraph("<b>Generated by:</b> EmailGuard Advanced Security Suite", normal_style))
    story.append(Paragraph(f"<b>Timestamp:</b> {report_data.get('timestamp', 'N/A')}", normal_style))
    story.append(Spacer(1, 15))
    
    story.append(Paragraph("1. Email Header & Domain Authentication", heading_style))
    header_info = [
        ["Sender Email:", report_data.get('sender', 'Unknown')],
        ["Subject:", report_data.get('subject', 'Unknown')],
        ["SPF Status:", report_data.get('spf', 'N/A')],
        ["DKIM Status:", report_data.get('dkim', 'N/A')],
        ["DMARC Status:", report_data.get('dmarc', 'N/A')],
    ]
    t1 = Table(header_info, colWidths=[120, 380])
    t1.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#f1f5f9")), ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#cbd5e1")), ('PADDING', (0,0), (-1,-1), 6)]))
    story.append(t1)
    story.append(Spacer(1, 12))
    
    story.append(Paragraph("2. Threat Intelligence & IP Geolocation", heading_style))
    ip_info = [
        ["Sender IP Address:", report_data.get('ip', 'N/A')],
        ["Country Location:", report_data.get('country', 'N/A')],
        ["ISP / Organization:", report_data.get('isp', 'N/A')],
    ]
    t2 = Table(ip_info, colWidths=[120, 380])
    t2.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#fef3c7")), ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#fde68a")), ('PADDING', (0,0), (-1,-1), 6)]))
    story.append(t2)
    story.append(Spacer(1, 12))
    
    story.append(Paragraph("3. Content Inspection & Risk Assessment", heading_style))
    risk_score = report_data.get('risk_score', 0)
    status_text = "HIGH RISK / PHISHING" if risk_score >= 50 else "LOW RISK / CLEAN"
    risk_info = [
        ["Final Risk Score:", f"{risk_score} / 100"],
        ["System Status:", status_text],
        ["Detected Alerts:", report_data.get('alerts_summary', 'None')],
    ]
    t3 = Table(risk_info, colWidths=[120, 380])
    t3.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#fee2e2") if risk_score >= 50 else colors.HexColor("#dcfce7")), ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#fca5a5") if risk_score >= 50 else colors.HexColor("#86efac")), ('PADDING', (0,0), (-1,-1), 6)]))
    story.append(t3)
    
    doc.build(story)
    return output_filename

